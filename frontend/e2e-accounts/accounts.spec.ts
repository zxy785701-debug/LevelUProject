test('暂停刷新恢复、断网不入账、错题复习不加奖励', async ({ page, request }) => {
  await login(page, request)
  await begin(page)
  await page.locator('.option').nth(1).click()
  await expect(page.locator('.feedback')).toBeVisible()
  await page.locator('.mini-back').click()
  await page.getByText('保存进度并离开', { exact: true }).click()
  await page.reload()
  await page.getByText('继续', { exact: true }).click()
  await expect(page.locator('.feedback')).toBeVisible()
  await page.getByText('下一题', { exact: true }).click()
  await expect(page.locator('.question')).toHaveText('第 2 个问题？')
  await page.route('**/attempts/*/answers', route => route.abort())
  await page.locator('.option').nth(0).click()
  await page.locator('.option').nth(1).click()
  await page.getByText('提交答案', { exact: true }).click()
  await expect(page.getByText('答案尚未确认', { exact: true })).toBeVisible()
  await expect(page.locator('.feedback')).toHaveCount(0)
  await page.getByText('知道了', { exact: true }).click()
  await page.unroute('**/attempts/*/answers')
  await page.getByText('提交答案', { exact: true }).click()
  await expect(page.locator('.feedback')).toBeVisible()
  await page.getByText('下一题', { exact: true }).click()
  await answer(page, 2, true, true)
  await page.reload()
  await page.getByText('复盘', { exact: true }).click()
  await page.getByText('错题本', { exact: true }).click()
  await page.screenshot({ path: '../docs/user-system/screenshots/R08-390.png' })
  await page.getByText('开始复习', { exact: true }).click()
  await page.locator('.option').nth(0).click()
  await expect(page.locator('.feedback')).toBeVisible()
  await page.getByText('完成这一关', { exact: true }).click()
  await page.getByText('返回错题本', { exact: true }).click()
  await page.getByText('已掌握 1', { exact: true }).click()
  await expect(page.getByText('第 1 个问题？', { exact: true })).toBeVisible()
})
test('账号隔离与过期回登录', async ({ page, request }) => {
  const first = await login(page, request)
  await begin(page)
  await page.reload()
  const other = await request.post('http://127.0.0.1:8001/api/v1/auth/wechat', { data: { code: `other-${Date.now()}`, agreement_version: '2026-10-12' } })
  const second = (await other.json()).data
  await page.evaluate(token => localStorage.setItem('levelup.auth.v1', JSON.stringify({ data: { token }, expire: null })), second.token)
  await page.reload()
  await expect(page.locator('textarea')).toBeVisible()
  await expect(page.getByText('继续', { exact: true })).toHaveCount(0)
  await request.post('http://127.0.0.1:8001/api/v1/auth/logout', { headers: { Authorization: `Bearer ${second.token}` } })
  await page.reload()
  await expect(page.getByText('保存你的学习旅程', { exact: true })).toBeVisible()
})
