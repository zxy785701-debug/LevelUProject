import { test, expect, Page, APIRequestContext } from '@playwright/test'
import fs from 'node:fs'
test.beforeEach(async ({ page }) => {
  await page.route('**/api/v1/**', async route => {
    const url = new URL(route.request().url()); url.port = '8001'
    const response = await route.fetch({ url: url.toString() })
    await route.fulfill({ response })
  })
})
async function login(page: Page, request: APIRequestContext, code = `e2e-${Date.now()}-${Math.random()}`) {
  const response = await request.post('http://127.0.0.1:8001/api/v1/auth/wechat', { data: { code, agreement_version: '2026-10-12' } })
  expect(response.status()).toBe(200)
  const session = (await response.json()).data
  await page.goto('/')
  await page.evaluate(token => localStorage.setItem('levelup.auth.v1', JSON.stringify({ data: { token }, expire: null })), session.token)
  await page.reload()
  await expect(page.locator('textarea')).toBeVisible()
  await expect(page.getByText('正在同步云端学习记录…')).toHaveCount(0)
  return session
}
async function begin(page: Page, count = 3) {
  await page.locator('textarea').fill('HTTP 为什么是无状态的？')
  if (count === 3) { await page.getByText('出题设置', { exact: false }).click(); await page.getByText('3 题', { exact: true }).click() }
  await page.getByText('生成我的关卡', { exact: false }).click()
  await page.getByText('开始这一关', { exact: true }).click()
}
async function answer(page: Page, index: number, correct = true, last = false) {
  await expect(page.locator('.question')).toHaveText(`第 ${index + 1} 个问题？`)
  const multi = index === 1
  const selected = correct ? (multi ? [0, 1] : [0]) : [1]
  for (const i of selected) await page.locator('.option').nth(i).click()
  if (multi) await page.getByText('提交答案', { exact: true }).click()
  await expect(page.locator('.feedback')).toBeVisible()
  await page.getByText(last ? '完成这一关' : '下一题', { exact: true }).click()
  if (last) await expect(page.locator('.result-score')).toBeVisible()
  else await expect(page.locator('.question')).toHaveText(`第 ${index + 2} 个问题？`)
}
